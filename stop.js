// Stops every running copy of this translator and cleans up what it created.
//
//   npm run stop      → stop all copies (including ones frozen with Ctrl+Z) and clear generated images
//   (automatic)       → index.js calls stopOtherCopies() on startup, so a new `npm start` takes over cleanly
//
// Only processes started from THIS project folder are touched, so other Node apps are safe.

const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const PROJECT_DIR = __dirname;
const IMAGES_DIR = path.join(PROJECT_DIR, 'images');

// Commands that belong to this app: `node index.js`, `node --watch index.js`, `npm start`, `npm run dev`
const APP_COMMAND = /(^|\/)(node(\s+--\S+)*\s+index\.js|npm(\s+run)?\s+(start|dev))(\s|$)/;

function listProcesses() {
  try {
    return execSync('ps -axo pid=,ppid=,stat=,command=', { encoding: 'utf8' })
      .split('\n')
      .map(line => line.trim().match(/^(\d+)\s+(\d+)\s+(\S+)\s+(.*)$/))
      .filter(Boolean)
      .map(([, pid, ppid, stat, command]) => ({ pid: Number(pid), ppid: Number(ppid), stat, command }));
  } catch (_) {
    return [];
  }
}

function getCwd(pid) {
  try {
    return fs.readlinkSync(`/proc/${pid}/cwd`); // Linux
  } catch (_) {
    try {
      const out = execSync(`lsof -a -p ${pid} -d cwd -Fn`, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] });
      const line = out.split('\n').find(l => l.startsWith('n'));
      return line ? line.slice(1) : null; // macOS
    } catch (_) {
      return null;
    }
  }
}

// This process and everything that launched it (e.g. the `npm start` running us) must be left alone
function getAncestors(processes) {
  const byPid = new Map(processes.map(p => [p.pid, p]));
  const ancestors = new Set([process.pid]);
  let current = byPid.get(process.pid);
  while (current && current.ppid > 1 && !ancestors.has(current.ppid)) {
    ancestors.add(current.ppid);
    current = byPid.get(current.ppid);
  }
  return ancestors;
}

function findOtherCopies() {
  const processes = listProcesses();
  const ancestors = getAncestors(processes);
  return processes.filter(p =>
    !ancestors.has(p.pid) &&
    !p.stat.startsWith('Z') &&           // zombies are already dead; they vanish when their parent is stopped
    APP_COMMAND.test(p.command) &&
    getCwd(p.pid) === PROJECT_DIR);
}

const isAlive = (pid) => {
  try { process.kill(pid, 0); return true; } catch (_) { return false; }
};

function sleepMs(ms) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}

/**
 * Stop other copies of the app: ask nicely (SIGTERM, which runs the app's graceful
 * shutdown), wake any that are frozen so they can act on it, then force-kill stragglers.
 * @returns {object[]} the processes that were stopped
 */
function stopOtherCopies({ quiet = false } = {}) {
  const copies = findOtherCopies();
  if (!copies.length) return [];

  for (const { pid } of copies) {
    try { process.kill(pid, 'SIGTERM'); } catch (_) {}
    try { process.kill(pid, 'SIGCONT'); } catch (_) {} // a Ctrl+Z'd process only handles SIGTERM once resumed
  }

  // The app's shutdown force-exits after 3s, so give it a little longer than that
  const deadline = Date.now() + 4000;
  while (copies.some(p => isAlive(p.pid)) && Date.now() < deadline) sleepMs(100);

  for (const { pid } of copies) {
    if (isAlive(pid)) {
      try { process.kill(pid, 'SIGKILL'); } catch (_) {}
    }
  }

  if (!quiet) {
    for (const p of copies) console.log(`✦ Stopped old copy: PID ${p.pid} (${p.command.trim()})${p.stat.startsWith('T') ? ' [was frozen]' : ''}`);
  }
  return copies;
}

// Remove images generated by /api/translate and /api/image
function cleanGeneratedFiles() {
  let removed = 0;
  try {
    for (const file of fs.readdirSync(IMAGES_DIR)) {
      if (file.endsWith('.png')) {
        fs.unlinkSync(path.join(IMAGES_DIR, file));
        removed++;
      }
    }
  } catch (_) { /* no images dir yet */ }
  return removed;
}

module.exports = { stopOtherCopies, cleanGeneratedFiles, findOtherCopies };

if (require.main === module) {
  const stopped = stopOtherCopies();
  const removed = cleanGeneratedFiles();
  if (!stopped.length) console.log('✦ No running copies of the translator found.');
  console.log(`✦ Removed ${removed} generated image${removed === 1 ? '' : 's'}. All clean.`);
}
